-- LocalSync initial schema.
-- Conventions: UUID primary keys, timestamptz everywhere, all constraints in the database
-- (the application validates too, but the database is the last line of defence).

-- ---------------------------------------------------------------- accounts
CREATE TABLE users (
  id            uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Always stored lower-cased; the CHECK makes a non-normalised insert impossible.
  email         text        NOT NULL CHECK (email = lower(email) AND length(email) BETWEEN 3 AND 254),
  display_name  text        NOT NULL CHECK (length(display_name) BETWEEN 1 AND 80),
  -- scrypt$N$r$p$salt$hash. Never the password itself.
  password_hash text        NOT NULL,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON users (email);

-- Server-side sessions: logging out (or an admin) revokes access immediately, which a
-- stateless JWT cannot do. Only a SHA-256 of the cookie value is stored, so a database
-- leak does not leak usable session tokens.
CREATE TABLE sessions (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash bytea       NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  user_agent text
);
CREATE UNIQUE INDEX sessions_token_hash_key ON sessions (token_hash);
CREATE INDEX sessions_user_id_idx ON sessions (user_id);
CREATE INDEX sessions_expires_at_idx ON sessions (expires_at);

-- --------------------------------------------------------------- documents
CREATE TYPE document_role AS ENUM ('owner', 'editor', 'viewer');

-- Metadata only. The id is generated by the CLIENT so a document can be created offline.
-- The rich-text body is a Yjs document stored in document_states, never in this table.
CREATE TABLE documents (
  id         uuid        PRIMARY KEY,
  title      text        NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Authorisation lives here: no row, no access. The owner is a member with role 'owner'.
CREATE TABLE document_members (
  document_id uuid          NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
  user_id     uuid          NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role        document_role NOT NULL,
  created_at  timestamptz   NOT NULL DEFAULT now(),
  PRIMARY KEY (document_id, user_id)
);
CREATE INDEX document_members_user_id_idx ON document_members (user_id);
-- Exactly one owner per document, enforced by the database.
CREATE UNIQUE INDEX document_members_one_owner ON document_members (document_id) WHERE role = 'owner';

-- The merged Yjs state of each document: one encoded update (see backend/src/realtime).
CREATE TABLE document_states (
  document_id uuid        PRIMARY KEY REFERENCES documents (id) ON DELETE CASCADE,
  state       bytea       NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);
